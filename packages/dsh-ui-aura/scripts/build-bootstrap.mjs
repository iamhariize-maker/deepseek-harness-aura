// Mechanical extraction keeps the host's pre-paint assets identical to the client.
import { readFileSync, writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('lib/client.js', root), 'utf8');
const styleStart = source.indexOf('const AURA_CSS =');
const styleEnd = source.indexOf('`;', styleStart) + 2;
const themeStart = source.indexOf('const AURA_THEMES =');
const themeEnd = source.indexOf('function defaultRecipe()', themeStart);
if (styleStart < 0 || styleEnd < styleStart || themeStart < 0 || themeEnd < themeStart) throw Error('Aura extraction markers changed');
const css = runInNewContext(source.slice(styleStart, styleEnd) + '; AURA_CSS');
const themeSource = source.slice(themeStart, themeEnd);
const skinIds = runInNewContext(themeSource + '; AURA_THEMES.map(theme => theme.id)');
const bootstrap = `(() => {\n${themeSource}\nconst settings = window.__AURA_BOOT__; if (settings) { applyTheme(settings.skin); applyVisualSettings(settings); }\n})()`;
if (/<\/style/i.test(css) || /<\/script/i.test(bootstrap)) throw Error('Unsafe inline asset');
writeFileSync(new URL('lib/bootstrap.generated.js', root), '// Generated by npm run build; do not edit.\n' +
  `export const css = ${JSON.stringify(css)};\nexport const bootstrap = ${JSON.stringify(bootstrap)};\nexport const skinIds = ${JSON.stringify(skinIds)};\n`);
console.log(`Built offline bootstrap: ${skinIds.length} skins, ${css.length} CSS characters.`);
